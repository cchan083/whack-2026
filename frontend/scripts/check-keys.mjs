import { chromium } from "playwright";
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type()==="error" && errs.push(m.text()));
await p.goto("http://localhost:5173/#wildfire?gap=4", { waitUntil: "networkidle" });
await p.waitForSelector(".scatterlayer"); await p.waitForTimeout(800);
const cur = () => p.evaluate(() => [document.querySelector('.gap-row[aria-current="true"]')?.dataset.index, location.hash, document.activeElement?.className]);
console.log("hash gap=4 ->", await cur());
await p.keyboard.press("j"); await p.waitForTimeout(100); console.log("j ->", await cur());
await p.keyboard.press("k"); await p.keyboard.press("k"); await p.waitForTimeout(100); console.log("kk ->", await cur());
await p.focus('.gap-row[aria-current="true"]'); await p.keyboard.press("End"); await p.waitForTimeout(100); console.log("End ->", await cur());
await p.keyboard.press("ArrowUp"); console.log("Up ->", await cur());
await p.keyboard.press("Home"); console.log("Home ->", await cur());
const r0 = await p.evaluate(() => document.querySelector(".js-plotly-plot")._fullLayout.xaxis.range);
await p.keyboard.press("ArrowDown"); await p.waitForTimeout(900);
const r1 = await p.evaluate(() => document.querySelector(".js-plotly-plot")._fullLayout.xaxis.range);
console.log("range before/after fly", r0, r1);
await p.evaluate(() => (location.hash = "#wildfire?gap=7")); await p.waitForTimeout(300); console.log("hashchange ->", await cur());
await p.keyboard.press("Control+k"); await p.waitForTimeout(200);
console.log("switcher open:", await p.evaluate(() => !!document.querySelector("dialog[open]")), "focus:", await p.evaluate(() => document.activeElement?.getAttribute("aria-label")));
await p.keyboard.type("topo"); await p.keyboard.press("Enter"); await p.waitForTimeout(1500); console.log("after switch ->", await cur());
console.log("errors", errs); await b.close();
